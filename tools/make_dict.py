"""Builds src/dict_data.c from the pyspellchecker English word list (the same one the
Python version of Amber Writer uses), so the .exe carries its own dictionary.

Format: words sorted in byte order, front coded. Each entry is
  [bytes shared with the previous word][frequency class 0-31][rest of the word][0]
where the frequency class is roughly log2 of how common the word is.
"""

import gzip
import json
import math
import os
import re
import sys

import spellchecker

WORD = re.compile(r"[a-z]+(?:'[a-z]+)*\Z")

src = os.path.join(os.path.dirname(spellchecker.__file__), "resources", "en.json.gz")
freq = json.load(gzip.open(src))
words = sorted(w for w in freq if WORD.match(w) and len(w) < 64)

out = bytearray()
prev = ""
for w in words:
    shared = 0
    while shared < min(len(prev), len(w), 63) and prev[shared] == w[shared]:
        shared += 1
    out.append(shared)
    out.append(min(31, int(math.log2(max(1, freq[w])))))
    out += w[shared:].encode("ascii")
    out.append(0)
    prev = w

dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "src", "dict_data.c")
with open(dest, "w") as f:
    f.write("/* Generated by tools/make_dict.py from the pyspellchecker English list. */\n")
    f.write("#include \"spell.h\"\n\n")
    f.write(f"const int dict_word_count = {len(words)};\n")
    f.write(f"const unsigned int dict_data_size = {len(out)};\n")
    f.write("const unsigned char dict_data[] =\n")
    for i in range(0, len(out), 32):
        chunk = out[i:i + 32]
        f.write("    \"" + "".join(f"\\x{b:02x}" for b in chunk) + "\"\n")
    f.write(";\n")
print(len(words), "words,", len(out), "bytes")
